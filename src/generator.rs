#[cfg(test)]
mod tests {
    use super::*;
    use crate::state;

    const SAMPLE_STATE: &str = r#"{
        "version": 4,
        "terraform_version": "1.6.0",
        "resources": [
            {
                "mode": "managed",
                "type": "aws_vpc",
                "name": "main",
                "provider": "provider[\"registry.terraform.io/hashicorp/aws\"]",
                "instances": [{
                    "attributes": {
                        "id": "vpc-abc123",
                        "cidr_block": "10.0.0.0/16",
                        "enable_dns_support": true,
                        "tags": {"Name": "main"}
                    },
                    "sensitive_attributes": []
                }]
            },
            {
                "mode": "managed",
                "type": "aws_db_instance",
                "name": "primary",
                "provider": "provider[\"registry.terraform.io/hashicorp/aws\"]",
                "instances": [{
                    "attributes": {
                        "id": "mydb",
                        "engine": "postgres",
                        "password": "s3cr3t",
                        "username": "admin",
                        "instance_class": "db.t3.micro"
                    },
                    "sensitive_attributes": [["password"]]
                }]
            },
            {
                "mode": "data",
                "type": "aws_ami",
                "name": "ubuntu",
                "provider": "provider[\"registry.terraform.io/hashicorp/aws\"]",
                "instances": [{
                    "attributes": {
                        "id": "ami-12345",
                        "most_recent": true,
                        "owners": ["099720109477"]
                    },
                    "sensitive_attributes": []
                }]
            }
        ]
    }"#;

    fn get_hcl() -> String {
        let json: serde_json::Value = serde_json::from_str(SAMPLE_STATE).unwrap();
        let resources = state::parse_state(&json).unwrap();
        generate_hcl(&resources)
    }

    #[test]
    fn has_terraform_block() {
        let hcl = get_hcl();
        assert!(hcl.contains("terraform {"), "missing terraform block");
        assert!(hcl.contains("required_providers {"), "missing required_providers");
        assert!(hcl.contains(r#"source = "hashicorp/aws""#), "missing provider source");
    }

    #[test]
    fn has_provider_skeleton() {
        let hcl = get_hcl();
        assert!(hcl.contains(r#"provider "aws" {"#), "missing provider block");
    }

    #[test]
    fn has_import_blocks() {
        let hcl = get_hcl();
        assert!(hcl.contains("import {"), "missing import block");
        assert!(hcl.contains("to = aws_vpc.main"), "missing import to address");
        assert!(hcl.contains(r#"id = "vpc-abc123""#), "missing import id");
    }

    #[test]
    fn id_not_in_resource_body() {
        let hcl = get_hcl();
        // Split at the resource block start and check its body has no `  id =`
        let after_resource = hcl
            .split(r#"resource "aws_vpc" "main" {"#)
            .nth(1)
            .expect("resource block missing");
        let body = after_resource.split('}').next().unwrap_or("");
        assert!(!body.contains("  id ="), "id must not appear in resource body");
    }

    #[test]
    fn sensitive_attr_is_null() {
        let hcl = get_hcl();
        assert!(
            hcl.contains("password = null # sensitive"),
            "sensitive attr must be nulled"
        );
    }

    #[test]
    fn data_source_uses_data_keyword() {
        let hcl = get_hcl();
        assert!(hcl.contains(r#"data "aws_ami" "ubuntu" {"#), "data source must use data keyword");
        assert!(!hcl.contains(r#"resource "aws_ami""#), "data source must not use resource keyword");
    }

    #[test]
    fn no_import_for_data_source() {
        let hcl = get_hcl();
        assert!(!hcl.contains("to = aws_ami.ubuntu"), "data source must not have import block");
    }
}
